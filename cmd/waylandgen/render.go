package main

import (
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
)

const generatedHeader = "// Code generated by waylandgen; DO NOT EDIT.\n\n"

type renderedFile struct {
	Rel  string
	Data []byte
}

// renderCorpus renders every output file in memory and gofmt's it. No file is
// written here; a render error leaves the tree untouched.
func renderCorpus(c *corpus) ([]renderedFile, error) {
	var files []renderedFile
	rootGen, rootMeta, err := renderRoot(c)
	if err != nil {
		return nil, err
	}
	files = append(files,
		renderedFile{Rel: "protocol_gen.go", Data: rootGen},
		renderedFile{Rel: "protocol_meta_gen.go", Data: rootMeta},
	)
	for _, pk := range c.pkgs {
		if pk.ImportPath == "" {
			continue
		}
		data, err := renderPackage(c, pk)
		if err != nil {
			return nil, err
		}
		files = append(files, renderedFile{Rel: pk.OutFile, Data: data})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Rel < files[j].Rel })
	return files, nil
}

type renderCtx struct {
	c       *corpus
	pk      *pkg
	aliases map[*pkg]string
	body    strings.Builder
}

func newRenderCtx(c *corpus, pk *pkg) *renderCtx {
	need := collectImports(pk)
	return &renderCtx{c: c, pk: pk, aliases: assignAliases(pk, need)}
}

func (r *renderCtx) isRoot() bool { return r.pk.ImportPath == "" }

func (r *renderCtx) proxyType() string {
	if r.isRoot() {
		return "*Proxy"
	}
	return "*wayland.Proxy"
}

func (r *renderCtx) qual(p *pkg) string {
	if p == r.pk {
		return ""
	}
	if p.ImportPath == "" {
		return "wayland."
	}
	return r.aliases[p] + "."
}

func (r *renderCtx) typeExpr(t *iface) string {
	return r.qual(t.Pkg) + t.GoName
}

func (r *renderCtx) handlerExpr(t *iface) string {
	return r.qual(t.Pkg) + t.HandlerName
}

func (r *renderCtx) newExpr(t *iface) string {
	return r.qual(t.Pkg) + "New" + t.GoName
}

func (r *renderCtx) enumExpr(t *iface, en *enum) string {
	return r.qual(t.Pkg) + t.GoName + en.GoName
}

func (r *renderCtx) errExpr(name string) string {
	if r.isRoot() {
		return name
	}
	return "wayland." + name
}

func (r *renderCtx) metaExpr(t *iface) string {
	if !r.isRoot() && t.Pkg == r.pk && t.IsLoser {
		return "interface" + t.GoName
	}
	if r.isRoot() {
		return "MustInterface(" + strconv.Quote(t.Name) + ")"
	}
	return "wayland.MustInterface(" + strconv.Quote(t.Name) + ")"
}

func collectImports(pk *pkg) map[*pkg]bool {
	need := make(map[*pkg]bool)
	for _, i := range pk.Interfaces {
		for _, m := range i.Requests {
			for _, a := range m.Args {
				if a.Target != nil && a.Target.Pkg != pk && a.Target.Pkg.ImportPath != "" {
					need[a.Target.Pkg] = true
				}
				if a.EnumTarget != nil && a.EnumTarget.Pkg != pk && a.EnumTarget.Pkg.ImportPath != "" {
					need[a.EnumTarget.Pkg] = true
				}
			}
		}
	}
	return need
}

func assignAliases(pk *pkg, need map[*pkg]bool) map[*pkg]string {
	aliases := make(map[*pkg]string)
	seen := map[string]bool{"wayland": true, "fmt": true}
	var list []*pkg
	for p := range need {
		if p != pk {
			list = append(list, p)
		}
	}
	sort.Slice(list, func(i, j int) bool { return list[i].ImportPath < list[j].ImportPath })
	for _, p := range list {
		cand := p.Name
		if seen[cand] || cand == "" {
			cand = packageName(p.Tier) + p.Name
		}
		if !token.IsIdentifier(cand) || token.IsKeyword(cand) {
			cand = "pkg" + p.Name
		}
		base := cand
		for n := 2; seen[cand] || !token.IsIdentifier(cand) || token.IsKeyword(cand); n++ {
			cand = base + strconv.Itoa(n)
		}
		seen[cand] = true
		aliases[p] = cand
	}
	return aliases
}

func renderRoot(c *corpus) ([]byte, []byte, error) {
	rc := newRenderCtx(c, c.root)
	for _, i := range c.root.Interfaces {
		if err := rc.renderInterface(i); err != nil {
			return nil, nil, err
		}
	}
	gen, err := rc.finish("wayland")
	if err != nil {
		return nil, nil, err
	}
	meta, err := renderRootMeta(c)
	if err != nil {
		return nil, nil, err
	}
	return gen, meta, nil
}

func renderPackage(c *corpus, pk *pkg) ([]byte, error) {
	rc := newRenderCtx(c, pk)
	for _, i := range pk.Interfaces {
		if err := rc.renderInterface(i); err != nil {
			return nil, err
		}
	}
	for _, i := range pk.LocalMeta {
		fmt.Fprintf(&rc.body, "var interface%s = %s\n\n", i.GoName, renderInterfaceLiteral(i, "wayland."))
	}
	return rc.finish(pk.Name)
}

func (r *renderCtx) finish(pkgName string) ([]byte, error) {
	body := r.body.String()
	usesFmt := strings.Contains(body, "fmt.")
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkgName)
	if r.isRoot() {
		if usesFmt {
			b.WriteString("import \"fmt\"\n\n")
		}
	} else {
		b.WriteString("import (\n")
		if usesFmt {
			b.WriteString("\t\"fmt\"\n\n")
		}
		fmt.Fprintf(&b, "\t%q\n", modulePath)
		var cross []*pkg
		for p := range r.aliases {
			cross = append(cross, p)
		}
		sort.Slice(cross, func(i, j int) bool { return cross[i].ImportPath < cross[j].ImportPath })
		for _, p := range cross {
			alias := r.aliases[p]
			if alias == p.Name {
				fmt.Fprintf(&b, "\t%q\n", p.ImportPath)
			} else {
				fmt.Fprintf(&b, "\t%s %q\n", alias, p.ImportPath)
			}
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(body)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, inputError("", pkgName, fmt.Errorf("gofmt generated source: %w", err))
	}
	return src, nil
}

func (r *renderCtx) renderInterface(i *iface) error {
	for _, en := range i.Enums {
		r.renderEnum(i, en)
	}
	r.renderType(i)
	r.renderProxy(i)
	r.renderNew(i)
	r.renderHandler(i)
	r.renderDispatch(i)
	for _, m := range i.Requests {
		if m.Dynamic() {
			if err := r.renderDynamicBind(i, m); err != nil {
				return err
			}
			continue
		}
		if err := r.renderRequest(i, m); err != nil {
			return err
		}
	}
	if !i.IsLoser {
		r.renderBind(i)
	}
	return nil
}

func (m *msg) Dynamic() bool {
	for _, a := range m.Args {
		if a.Dynamic {
			return true
		}
	}
	return false
}

func (r *renderCtx) renderEnum(i *iface, en *enum) {
	typeName := i.GoName + en.GoName
	underlying := "int32"
	unsigned := en.Bitfield
	for _, e := range en.Entries {
		if e.Value > 1<<31-1 {
			unsigned = true
		}
	}
	if unsigned {
		underlying = "uint32"
	}
	fmt.Fprintf(&r.body, "type %s %s\n\n", typeName, underlying)
	if len(en.Entries) == 0 {
		return
	}
	r.body.WriteString("const (\n")
	for _, e := range en.Entries {
		fmt.Fprintf(&r.body, "\t%s%s %s = %s\n", typeName, e.GoName, typeName, literalInt64(e.Value))
	}
	r.body.WriteString(")\n\n")
}

func (r *renderCtx) renderType(i *iface) {
	fmt.Fprintf(&r.body, "type %s struct {\n\tp %s\n", i.GoName, r.proxyType())
	if i.HasEvents && !i.IsDisplay {
		fmt.Fprintf(&r.body, "\th %s\n", i.HandlerName)
	}
	r.body.WriteString("}\n\n")
}

func (r *renderCtx) renderProxy(i *iface) {
	recv := receiverName(i)
	fmt.Fprintf(&r.body, "func (%s *%s) Proxy() %s {\n\treturn %s.p\n}\n\n", recv, i.GoName, r.proxyType(), recv)
}

func (r *renderCtx) renderNew(i *iface) {
	if !i.HasEvents || i.IsDisplay {
		fmt.Fprintf(&r.body, "func New%s(p %s) *%s {\n\treturn &%s{p: p}\n}\n\n", i.GoName, r.proxyType(), i.GoName, i.GoName)
		return
	}
	fmt.Fprintf(&r.body, "func New%s(p %s, h %s) *%s {\n", i.GoName, r.proxyType(), i.HandlerName, i.GoName)
	fmt.Fprintf(&r.body, "\tobj := &%s{p: p, h: h}\n", i.GoName)
	r.body.WriteString("\tif h != nil {\n\t\t_ = p.SetSink(obj)\n\t}\n")
	if i.Name == "wl_callback" {
		r.body.WriteString("\tp.markServerOwned()\n")
	}
	r.body.WriteString("\treturn obj\n}\n\n")
}

func (r *renderCtx) renderHandler(i *iface) {
	if !i.HasEvents || i.IsDisplay {
		return
	}
	fmt.Fprintf(&r.body, "type %s interface {\n", i.HandlerName)
	if r.isRoot() && i.Name == "wl_registry" {
		r.body.WriteString("\tGlobal(g Global)\n")
		r.body.WriteString("\tGlobalRemove(name uint32)\n")
		r.body.WriteString("}\n\n")
		return
	}
	for _, e := range i.Events {
		fmt.Fprintf(&r.body, "\t%s(%s)\n", e.GoName, r.eventParams(e))
	}
	r.body.WriteString("}\n\n")
}

func (r *renderCtx) renderDispatch(i *iface) {
	if !i.HasEvents || i.IsDisplay {
		return
	}
	recv := receiverName(i)
	fmt.Fprintf(&r.body, "func (%s *%s) DispatchEvent(opcode uint16, args []%s) error {\n", recv, i.GoName, r.argType())
	r.body.WriteString("\tswitch opcode {\n")
	if r.isRoot() && i.Name == "wl_registry" {
		r.body.WriteString("\tcase 0:\n")
		fmt.Fprintf(&r.body, "\t\t%s.h.Global(Global{Name: args[0].Uint(), Interface: args[1].String(), Version: args[2].Uint()})\n", recv)
		r.body.WriteString("\tcase 1:\n")
		fmt.Fprintf(&r.body, "\t\t%s.h.GlobalRemove(args[0].Uint())\n", recv)
	} else {
		for n, e := range i.Events {
			exprs := make([]string, 0, len(e.Args))
			for index, a := range e.Args {
				exprs = append(exprs, eventExpr(a, index))
			}
			fmt.Fprintf(&r.body, "\tcase %d:\n\t\t%s.h.%s(%s)\n", n, recv, e.GoName, strings.Join(exprs, ", "))
		}
	}
	fmt.Fprintf(&r.body, "\tdefault:\n\t\treturn fmt.Errorf(%q, opcode, %s)\n", i.GoName+" event %d: %w", r.errExpr("ErrProtocolViolation"))
	r.body.WriteString("\t}\n\treturn nil\n}\n\n")
}

func (r *renderCtx) argType() string {
	if r.isRoot() {
		return "Arg"
	}
	return "wayland.Arg"
}

func (r *renderCtx) eventParams(e *msg) string {
	used := map[string]bool{"args": true, "opcode": true}
	var parts []string
	for _, a := range e.Args {
		name := uniqueName(goParamName(a.Name), used)
		parts = append(parts, name+" "+r.eventArgType(a))
	}
	return strings.Join(parts, ", ")
}

func (r *renderCtx) eventArgType(a *arg) string {
	switch a.Type {
	case "int":
		return "int32"
	case "uint":
		return "uint32"
	case "fixed":
		return "float64"
	case "string":
		if a.AllowNull {
			return "*string"
		}
		return "string"
	case "array":
		return "[]byte"
	case "fd":
		return "int"
	case "object", "new_id":
		return r.proxyType()
	}
	return "any"
}

func eventExpr(a *arg, index int) string {
	switch a.Type {
	case "int":
		return fmt.Sprintf("args[%d].Int()", index)
	case "uint":
		return fmt.Sprintf("args[%d].Uint()", index)
	case "fixed":
		return fmt.Sprintf("args[%d].Fixed()", index)
	case "string":
		if a.AllowNull {
			return fmt.Sprintf("args[%d].StringPtr()", index)
		}
		return fmt.Sprintf("args[%d].String()", index)
	case "array":
		return fmt.Sprintf("args[%d].Array()", index)
	case "fd":
		return fmt.Sprintf("args[%d].FD()", index)
	case "object", "new_id":
		return fmt.Sprintf("args[%d].Proxy()", index)
	}
	return "nil"
}

func (r *renderCtx) renderRequest(i *iface, m *msg) error {
	var newID *arg
	for _, a := range m.Args {
		if a.Type == "new_id" {
			newID = a
		}
	}
	var target *iface
	if newID != nil {
		if newID.Dynamic {
			return inputError(i.Protocol.XML, i.Name+"."+m.Name, fmt.Errorf("dynamic new_id must use the wl_registry.bind template"))
		}
		target = newID.Target
		if target == nil {
			return inputError(i.Protocol.XML, i.Name+"."+m.Name+"."+newID.Name, fmt.Errorf("unresolved new_id target"))
		}
	}
	recv := receiverName(i)
	used := map[string]bool{recv: true, "h": true, "p": true, "err": true, "obj": true, "int32": true, "uint32": true}
	for _, alias := range r.aliases {
		used[alias] = true
	}
	used["wayland"] = true
	used["fmt"] = true

	var params []requestParam
	for _, a := range m.Args {
		if a.Type == "new_id" {
			continue
		}
		typ, err := r.requestArgType(a)
		if err != nil {
			return inputError(i.Protocol.XML, i.Name+"."+m.Name+"."+a.Name, err)
		}
		params = append(params, requestParam{arg: a, name: uniqueName(goParamName(a.Name), used), typ: typ})
	}
	hasHandler := target != nil && target.HasEvents && !target.IsDisplay
	var sig []string
	for _, p := range params {
		sig = append(sig, p.name+" "+p.typ)
	}
	if hasHandler {
		sig = append(sig, "h "+r.handlerExpr(target))
	}
	ret := "error"
	if target != nil {
		ret = "(*" + r.typeExpr(target) + ", error)"
	}
	fmt.Fprintf(&r.body, "func (%s *%s) %s(%s) %s {\n", recv, i.GoName, m.GoName, strings.Join(sig, ", "), ret)
	if hasHandler {
		fmt.Fprintf(&r.body, "\tif h == nil {\n\t\treturn nil, fmt.Errorf(%q, %s)\n\t}\n", m.Name+": %w", r.errExpr("ErrInvalidArgument"))
	}
	for _, p := range params {
		if p.arg.Type != "object" || p.arg.AllowNull {
			continue
		}
		if target != nil {
			fmt.Fprintf(&r.body, "\tif %s == nil {\n\t\treturn nil, fmt.Errorf(%q, %s)\n\t}\n", p.name, m.Name+": nil "+p.arg.Name+": %w", r.errExpr("ErrInvalidArgument"))
		} else {
			fmt.Fprintf(&r.body, "\tif %s == nil {\n\t\treturn fmt.Errorf(%q, %s)\n\t}\n", p.name, m.Name+": nil "+p.arg.Name+": %w", r.errExpr("ErrInvalidArgument"))
		}
	}
	var nullIDs = make(map[*arg]string)
	for index, p := range params {
		if p.arg.Type != "object" || !p.arg.AllowNull {
			continue
		}
		local := uniqueName("objID"+strconv.Itoa(index), used)
		nullIDs[p.arg] = local
		fmt.Fprintf(&r.body, "\tvar %s uint32\n\tif %s != nil {\n\t\t%s = %s.Proxy().ID()\n\t}\n", local, p.name, local, p.name)
	}
	if target != nil {
		fmt.Fprintf(&r.body, "\tp, err := %s.p.NewObject(%s)\n", recv, r.metaExpr(target))
		r.body.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		if hasHandler {
			fmt.Fprintf(&r.body, "\tobj := %s(p, h)\n", r.newExpr(target))
		} else {
			fmt.Fprintf(&r.body, "\tobj := %s(p)\n", r.newExpr(target))
		}
	}
	args, err := r.requestArgs(m, params, nullIDs)
	if err != nil {
		return inputError(i.Protocol.XML, i.Name+"."+m.Name, err)
	}
	if target != nil {
		fmt.Fprintf(&r.body, "\tif err := %s.p.Send(%d, %s); err != nil {\n\t\t_ = p.Release()\n\t\treturn nil, err\n\t}\n", recv, m.Opcode, strings.Join(args, ", "))
		r.body.WriteString("\treturn obj, nil\n")
	} else {
		if len(args) == 0 {
			fmt.Fprintf(&r.body, "\treturn %s.p.Send(%d)\n", recv, m.Opcode)
		} else {
			fmt.Fprintf(&r.body, "\treturn %s.p.Send(%d, %s)\n", recv, m.Opcode, strings.Join(args, ", "))
		}
	}
	r.body.WriteString("}\n\n")
	return nil
}

func (r *renderCtx) requestArgType(a *arg) (string, error) {
	if a.Enum != nil {
		if a.EnumTarget == nil {
			return "", fmt.Errorf("unresolved enum")
		}
		return r.enumExpr(a.EnumTarget, a.Enum), nil
	}
	switch a.Type {
	case "int":
		return "int32", nil
	case "uint":
		return "uint32", nil
	case "fixed":
		return "float64", nil
	case "string":
		if a.AllowNull {
			return "*string", nil
		}
		return "string", nil
	case "array":
		return "[]byte", nil
	case "fd":
		return "int", nil
	case "object":
		if a.Target == nil {
			return "", fmt.Errorf("object arg %s has no interface", a.Name)
		}
		return "*" + r.typeExpr(a.Target), nil
	}
	return "", fmt.Errorf("request arg type %q not implemented", a.Type)
}

type requestParam struct {
	arg  *arg
	name string
	typ  string
}

func (r *renderCtx) requestArgs(m *msg, params []requestParam, nullIDs map[*arg]string) ([]string, error) {
	byArg := make(map[*arg]requestParam, len(params))
	for _, p := range params {
		byArg[p.arg] = p
	}
	args := make([]string, 0, len(m.Args))
	for _, a := range m.Args {
		if a.Type == "new_id" {
			args = append(args, r.argCall("NewID")+"(p.ID())")
			continue
		}
		p, ok := byArg[a]
		if !ok {
			return nil, fmt.Errorf("arg %s is missing from the rendered signature", a.Name)
		}
		switch a.Type {
		case "int":
			if a.Enum != nil {
				args = append(args, r.argCall("Int")+"(int32("+p.name+"))")
			} else {
				args = append(args, r.argCall("Int")+"("+p.name+")")
			}
		case "uint":
			if a.Enum != nil {
				args = append(args, r.argCall("Uint")+"(uint32("+p.name+"))")
			} else {
				args = append(args, r.argCall("Uint")+"("+p.name+")")
			}
		case "fixed":
			args = append(args, r.argCall("Fixed")+"("+p.name+")")
		case "string":
			if a.AllowNull {
				args = append(args, r.argCall("String")+"("+p.name+")")
			} else {
				args = append(args, r.argCall("String")+"(&"+p.name+")")
			}
		case "array":
			args = append(args, r.argCall("Array")+"("+p.name+")")
		case "fd":
			args = append(args, r.argCall("FD")+"("+p.name+")")
		case "object":
			if a.AllowNull {
				args = append(args, r.argCall("Object")+"("+nullIDs[a]+")")
			} else {
				args = append(args, r.argCall("Object")+"("+p.name+".Proxy().ID())")
			}
		default:
			return nil, fmt.Errorf("arg %s: unsupported type %q", a.Name, a.Type)
		}
	}
	return args, nil
}

func (r *renderCtx) argCall(fn string) string {
	if r.isRoot() {
		return fn
	}
	return "wayland." + fn
}

func (r *renderCtx) renderDynamicBind(i *iface, m *msg) error {
	if !r.isRoot() || i.Name != "wl_registry" || m.Name != "bind" {
		return inputError(i.Protocol.XML, i.Name+"."+m.Name, fmt.Errorf("dynamic bind template is only valid for root wl_registry.bind"))
	}
	r.body.WriteString("func (r *Registry) Bind(g Global, version uint32) (*Proxy, error) {\n")
	r.body.WriteString("\tiface, ok := InterfaceByName(g.Interface)\n")
	r.body.WriteString("\tif !ok {\n\t\treturn nil, fmt.Errorf(\"bind %s: %w\", g.Interface, ErrInvalidArgument)\n\t}\n")
	r.body.WriteString("\tif version < 1 || version > g.Version || version > iface.Version {\n")
	r.body.WriteString("\t\treturn nil, fmt.Errorf(\"bind %s v%d: %w\", g.Interface, version, ErrVersion)\n\t}\n")
	r.body.WriteString("\tp, err := r.p.newObjectWithVersion(iface, version)\n")
	r.body.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	r.body.WriteString("\tif err := r.p.Send(0, Uint(g.Name), NewID(p.ID())); err != nil {\n")
	r.body.WriteString("\t\t_ = p.Release()\n\t\treturn nil, err\n\t}\n")
	r.body.WriteString("\treturn p, nil\n}\n\n")
	return nil
}

func (r *renderCtx) renderBind(i *iface) {
	hasHandler := i.HasEvents && !i.IsDisplay
	params := "r " + r.registryType() + ", g " + r.globalType()
	if hasHandler {
		params += ", h " + i.HandlerName
	}
	fmt.Fprintf(&r.body, "func Bind%s(%s) (*%s, error) {\n", i.GoName, params, i.GoName)
	if hasHandler {
		fmt.Fprintf(&r.body, "\tif h == nil {\n\t\treturn nil, fmt.Errorf(%q, %s)\n\t}\n", "bind "+i.GoName+": %w", r.errExpr("ErrInvalidArgument"))
	}
	fmt.Fprintf(&r.body, "\tv := min(g.Version, %s.Version)\n", r.metaExpr(i))
	r.body.WriteString("\tp, err := r.Bind(g, v)\n")
	r.body.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	if hasHandler {
		fmt.Fprintf(&r.body, "\treturn New%s(p, h), nil\n", i.GoName)
	} else {
		fmt.Fprintf(&r.body, "\treturn New%s(p), nil\n", i.GoName)
	}
	r.body.WriteString("}\n\n")
}

func (r *renderCtx) registryType() string {
	if r.isRoot() {
		return "*Registry"
	}
	return "*wayland.Registry"
}

func (r *renderCtx) globalType() string {
	if r.isRoot() {
		return "Global"
	}
	return "wayland.Global"
}

func metaVariableNames(c *corpus) map[*iface]string {
	metaVar := make(map[*iface]string, len(c.interfaces))
	used := make(map[string]bool, len(c.interfaces))
	for _, i := range c.interfaces {
		base := "interface" + i.GoName
		if i.Pkg.ImportPath != "" {
			base = "interface" + camel(packageName(i.Pkg.Tier)) + camel(packageName(i.Pkg.Dir)) + i.GoName
		}
		name := base
		for n := 2; used[name]; n++ {
			name = base + strconv.Itoa(n)
		}
		used[name] = true
		metaVar[i] = name
	}
	return metaVar
}

func renderRootMeta(c *corpus) ([]byte, error) {
	metaVar := metaVariableNames(c)
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("package wayland\n\n")
	for _, i := range c.interfaces {
		fmt.Fprintf(&b, "var %s = %s\n\n", metaVar[i], renderInterfaceLiteral(i, ""))
	}
	names := make([]string, 0, len(c.byName))
	for name := range c.byName {
		names = append(names, name)
	}
	sort.Strings(names)
	b.WriteString("var generatedInterfaces = map[string]*Interface{\n")
	for _, name := range names {
		winner := c.byName[name][0].Winner
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(name), metaVar[winner])
	}
	b.WriteString("}\n\n")
	b.WriteString("var allInterfaces = []*Interface{\n")
	for _, i := range c.interfaces {
		fmt.Fprintf(&b, "\t%s,\n", metaVar[i])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, inputError("", "protocol_meta_gen.go", fmt.Errorf("gofmt generated source: %w", err))
	}
	return src, nil
}

func renderInterfaceLiteral(i *iface, prefix string) string {
	var b strings.Builder
	b.WriteString("&" + prefix + "Interface{\n")
	fmt.Fprintf(&b, "\tName: %s,\n", strconv.Quote(i.Name))
	fmt.Fprintf(&b, "\tVersion: %d,\n", i.Version)
	if i.Frozen {
		b.WriteString("\tFrozen: true,\n")
	}
	if len(i.Requests) > 0 {
		b.WriteString("\tRequests: []" + prefix + "Message{\n")
		for _, m := range i.Requests {
			b.WriteString("\t\t" + renderMessageLiteral(m, prefix) + ",\n")
		}
		b.WriteString("\t},\n")
	}
	if len(i.Events) > 0 {
		b.WriteString("\tEvents: []" + prefix + "Message{\n")
		for _, m := range i.Events {
			b.WriteString("\t\t" + renderMessageLiteral(m, prefix) + ",\n")
		}
		b.WriteString("\t},\n")
	}
	if len(i.Enums) > 0 {
		b.WriteString("\tEnums: []" + prefix + "Enum{\n")
		for _, en := range i.Enums {
			b.WriteString("\t\t" + renderEnumLiteral(en, prefix) + ",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}")
	return b.String()
}

func renderMessageLiteral(m *msg, prefix string) string {
	var parts []string
	parts = append(parts, "Name: "+strconv.Quote(m.Name))
	parts = append(parts, fmt.Sprintf("Since: %d", m.Since))
	if m.DeprecatedSince != 0 {
		parts = append(parts, fmt.Sprintf("DeprecatedSince: %d", m.DeprecatedSince))
	}
	if m.Destructor {
		parts = append(parts, "Destructor: true")
	}
	if len(m.Args) > 0 {
		parts = append(parts, "Args: []"+prefix+"ArgSpec{"+renderArgsLiteral(m.Args, prefix)+"}")
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

func renderArgsLiteral(args []*arg, prefix string) string {
	parts := make([]string, 0, len(args))
	for _, a := range args {
		parts = append(parts, renderArgLiteral(a, prefix))
	}
	return strings.Join(parts, ", ")
}

func renderArgLiteral(a *arg, prefix string) string {
	var parts []string
	parts = append(parts, "Name: "+strconv.Quote(a.Name))
	parts = append(parts, "Type: "+prefix+argTypeConst(a.Type))
	if a.InterfaceName != "" {
		parts = append(parts, "Interface: "+strconv.Quote(a.InterfaceName))
	}
	if a.EnumName != "" {
		parts = append(parts, "Enum: "+strconv.Quote(a.EnumName))
	}
	if a.AllowNull {
		parts = append(parts, "AllowNull: true")
	}
	if a.Since != 0 {
		parts = append(parts, fmt.Sprintf("Since: %d", a.Since))
	}
	if a.DeprecatedSince != 0 {
		parts = append(parts, fmt.Sprintf("DeprecatedSince: %d", a.DeprecatedSince))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

func renderEnumLiteral(en *enum, prefix string) string {
	var parts []string
	parts = append(parts, "Name: "+strconv.Quote(en.Name))
	parts = append(parts, fmt.Sprintf("Since: %d", en.Since))
	if en.Bitfield {
		parts = append(parts, "Bitfield: true")
	}
	if len(en.Entries) > 0 {
		entries := make([]string, 0, len(en.Entries))
		for _, e := range en.Entries {
			var ep []string
			ep = append(ep, "Name: "+strconv.Quote(e.Name))
			ep = append(ep, "Value: "+literalInt64(e.Value))
			ep = append(ep, fmt.Sprintf("Since: %d", e.Since))
			if e.DeprecatedSince != 0 {
				ep = append(ep, fmt.Sprintf("DeprecatedSince: %d", e.DeprecatedSince))
			}
			entries = append(entries, "{"+strings.Join(ep, ", ")+"}")
		}
		parts = append(parts, "Entries: []"+prefix+"EnumEntry{"+strings.Join(entries, ", ")+"}")
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

func argTypeConst(t string) string {
	switch t {
	case "int":
		return "ArgInt"
	case "uint":
		return "ArgUint"
	case "fixed":
		return "ArgFixed"
	case "string":
		return "ArgString"
	case "array":
		return "ArgArray"
	case "fd":
		return "ArgFD"
	case "new_id":
		return "ArgNewID"
	case "object":
		return "ArgObject"
	}
	return "ArgUint"
}

func literalInt64(v int64) string {
	if v >= 0 {
		return fmt.Sprintf("0x%x", v)
	}
	return strconv.FormatInt(v, 10)
}

func receiverName(i *iface) string {
	name := lowerFirst(i.GoName)
	if name == "" || name == "_" || token.IsKeyword(name) || name == "p" || name == "err" || name == "obj" || name == "h" {
		return "receiver"
	}
	return name
}

var goKeywords = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true,
	"default": true, "defer": true, "else": true, "fallthrough": true, "for": true,
	"func": true, "go": true, "goto": true, "if": true, "import": true,
	"interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
}

var initialisms = map[string]string{
	"api":   "API",
	"fd":    "FD",
	"http":  "HTTP",
	"https": "HTTPS",
	"id":    "ID",
	"url":   "URL",
	"uuid":  "UUID",
}

// goParamName converts a wire argument name to an idiomatic Go parameter name.
func goParamName(s string) string {
	parts := strings.Split(strings.ReplaceAll(s, "-", "_"), "_")
	var b strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		if b.Len() == 0 {
			b.WriteString(part)
			continue
		}
		if up, ok := initialisms[part]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	name := b.String()
	if name == "" {
		return "arg"
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "arg" + name
	}
	if goKeywords[name] {
		name += "_"
	}
	return name
}

func uniqueName(base string, used map[string]bool) string {
	name := base
	if name == "" {
		name = "arg"
	}
	for used[name] {
		name += "_"
	}
	used[name] = true
	return name
}
