package main

import (
	"fmt"
	"go/format"
	"strings"
)

const generatedHeader = "// Code generated by waylandgen; DO NOT EDIT.\n\n"

func render(p *protocol) ([]byte, []byte, error) {
	byName := make(map[string]*iface, len(p.Interfaces))
	for _, i := range p.Interfaces {
		byName[i.Name] = i
	}
	var g strings.Builder
	g.WriteString(generatedHeader)
	g.WriteString("package wayland\n\n")
	g.WriteString("import \"fmt\"\n\n")
	for _, i := range p.Interfaces {
		renderType(&g, i)
		renderHandler(&g, i)
		renderDispatch(&g, i)
		for _, r := range i.Requests {
			if i.Name == "wl_registry" && r.Name == "bind" {
				renderRegistryBind(&g, i)
				continue
			}
			if err := renderRequest(&g, i, r, byName); err != nil {
				return nil, nil, err
			}
		}
		renderBindHelper(&g, i)
	}
	var m strings.Builder
	renderMeta(&m, p)
	gen, err := format.Source([]byte(g.String()))
	if err != nil {
		return nil, nil, fmt.Errorf("format protocol_gen.go: %w", err)
	}
	meta, err := format.Source([]byte(m.String()))
	if err != nil {
		return nil, nil, fmt.Errorf("format protocol_meta_gen.go: %w", err)
	}
	return gen, meta, nil
}

func renderType(b *strings.Builder, i *iface) {
	if i.HasEvents && !i.IsDisplay {
		fmt.Fprintf(b, "type %s struct {\n\tp *Proxy\n\th %s\n}\n\n", i.GoName, i.HandlerName)
		return
	}
	fmt.Fprintf(b, "type %s struct {\n\tp *Proxy\n}\n\n", i.GoName)
}

func renderHandler(b *strings.Builder, i *iface) {
	if !i.HasEvents || i.IsDisplay {
		return
	}
	switch i.Name {
	case "wl_registry":
		b.WriteString("type RegistryHandler interface {\n")
		b.WriteString("\tGlobal(g Global)\n")
		b.WriteString("\tGlobalRemove(name uint32)\n")
		b.WriteString("}\n\n")
		return
	case "wl_callback":
		b.WriteString("type CallbackHandler interface {\n")
		b.WriteString("\tDone(callbackData uint32)\n")
		b.WriteString("}\n\n")
		return
	}
	fmt.Fprintf(b, "type %s interface {\n", i.HandlerName)
	for _, e := range i.Events {
		fmt.Fprintf(b, "\t%s(%s)\n", e.GoName, eventParams(e))
	}
	b.WriteString("}\n\n")
}

func renderDispatch(b *strings.Builder, i *iface) {
	if !i.HasEvents || i.IsDisplay {
		return
	}
	recv := lowerFirst(i.GoName)
	fmt.Fprintf(b, "func (%s *%s) DispatchEvent(opcode uint16, args []Arg) error {\n", recv, i.GoName)
	b.WriteString("\tswitch opcode {\n")
	switch i.Name {
	case "wl_registry":
		b.WriteString("\tcase 0:\n")
		b.WriteString("\t\t" + recv + ".h.Global(Global{Name: args[0].Uint(), Interface: args[1].String(), Version: args[2].Uint()})\n")
		b.WriteString("\tcase 1:\n")
		b.WriteString("\t\t" + recv + ".h.GlobalRemove(args[0].Uint())\n")
	case "wl_callback":
		b.WriteString("\tcase 0:\n")
		b.WriteString("\t\t" + recv + ".h.Done(args[0].Uint())\n")
	default:
		for n, e := range i.Events {
			if len(e.Args) == 0 {
				fmt.Fprintf(b, "\tcase %d:\n\t\t%s.h.%s()\n", n, recv, e.GoName)
				continue
			}
			exprs := make([]string, 0, len(e.Args))
			for _, a := range e.Args {
				exprs = append(exprs, eventExpr(a, len(exprs)))
			}
			fmt.Fprintf(b, "\tcase %d:\n\t\t%s.h.%s(%s)\n", n, recv, e.GoName, strings.Join(exprs, ", "))
		}
	}
	fmt.Fprintf(b, "\tdefault:\n\t\treturn fmt.Errorf(\"%s event %%d: %%w\", opcode, ErrProtocolViolation)\n", i.GoName)
	b.WriteString("\t}\n\treturn nil\n}\n\n")
}

func renderRequest(b *strings.Builder, i *iface, r *msg, byName map[string]*iface) error {
	var newID *arg
	for _, a := range r.Args {
		if a.Type == "new_id" {
			newID = a
		}
	}
	var target *iface
	if newID != nil {
		if newID.Interface == "" {
			return fmt.Errorf("%s.%s: dynamic new_id must be special-cased", i.Name, r.Name)
		}
		target = byName[newID.Interface]
		if target == nil {
			return fmt.Errorf("%s.%s: unknown new_id target %q", i.Name, r.Name, newID.Interface)
		}
	}
	recv := lowerFirst(i.GoName)
	var params []string
	for _, a := range r.Args {
		if a.Type == "new_id" {
			continue
		}
		if a.Type == "object" {
			return fmt.Errorf("%s.%s.%s: object request args not implemented in S-01", i.Name, r.Name, a.Name)
		}
		t, err := requestArgType(a)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", i.Name, r.Name, err)
		}
		params = append(params, safeName(a.Name)+" "+t)
	}
	hasHandler := target != nil && target.HasEvents && !target.IsDisplay
	if hasHandler {
		params = append(params, "h "+target.HandlerName)
	}
	ret := "error"
	if target != nil {
		ret = "(*" + target.GoName + ", error)"
	}
	fmt.Fprintf(b, "func (%s *%s) %s(%s) %s {\n", recv, i.GoName, r.GoName, strings.Join(params, ", "), ret)
	if hasHandler {
		fmt.Fprintf(b, "\tif h == nil {\n\t\treturn nil, fmt.Errorf(\"%s: %%w\", ErrInvalidArgument)\n\t}\n", r.Name)
	}
	var pname string
	if target != nil {
		pname = "p"
		fmt.Fprintf(b, "\tp, err := %s.p.NewObject(mustInterface(\"%s\"))\n", recv, target.Name)
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		if hasHandler {
			fmt.Fprintf(b, "\tobj := &%s{p: p, h: h}\n", target.GoName)
			b.WriteString("\tif err := p.SetSink(obj); err != nil {\n\t\t_ = p.Release()\n\t\treturn nil, err\n\t}\n")
		} else {
			fmt.Fprintf(b, "\tobj := &%s{p: p}\n", target.GoName)
		}
		if target.Name == "wl_callback" {
			b.WriteString("\tp.markServerOwned()\n")
		}
	}
	args := make([]string, 0, len(r.Args))
	for _, a := range r.Args {
		if a.Type == "new_id" {
			args = append(args, "NewID("+pname+".ID())")
			continue
		}
		expr, err := requestExpr(a, safeName(a.Name))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", i.Name, r.Name, err)
		}
		args = append(args, expr)
	}
	if target != nil {
		fmt.Fprintf(b, "\tif err := %s.p.Send(%d, %s); err != nil {\n\t\t_ = p.Release()\n\t\treturn nil, err\n\t}\n", recv, opcodeOf(i, r), strings.Join(args, ", "))
		b.WriteString("\treturn obj, nil\n")
	} else {
		fmt.Fprintf(b, "\treturn %s.p.Send(%d, %s)\n", recv, opcodeOf(i, r), strings.Join(args, ", "))
	}
	b.WriteString("}\n\n")
	return nil
}

func renderRegistryBind(b *strings.Builder, i *iface) {
	b.WriteString("func (r *Registry) Bind(g Global, version uint32) (*Proxy, error) {\n")
	b.WriteString("\tiface, ok := InterfaceByName(g.Interface)\n")
	b.WriteString("\tif !ok {\n\t\treturn nil, fmt.Errorf(\"bind %s: %w\", g.Interface, ErrInvalidArgument)\n\t}\n")
	b.WriteString("\tif version < 1 || version > g.Version || version > iface.Version {\n")
	b.WriteString("\t\treturn nil, fmt.Errorf(\"bind %s v%d: %w\", g.Interface, version, ErrVersion)\n\t}\n")
	b.WriteString("\tp, err := r.p.newObjectWithVersion(iface, version)\n")
	b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\tif err := r.p.Send(0, Uint(g.Name), NewID(p.ID())); err != nil {\n")
	b.WriteString("\t\t_ = p.Release()\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\treturn p, nil\n}\n\n")
}

func renderBindHelper(b *strings.Builder, i *iface) {
	hasHandler := i.HasEvents && !i.IsDisplay
	params := "r *Registry, g Global"
	if hasHandler {
		params += ", h " + i.HandlerName
	}
	fmt.Fprintf(b, "func Bind%s(%s) (*%s, error) {\n", i.GoName, params, i.GoName)
	if hasHandler {
		fmt.Fprintf(b, "\tif h == nil {\n\t\treturn nil, fmt.Errorf(\"bind %s: %%w\", ErrInvalidArgument)\n\t}\n", i.GoName)
	}
	fmt.Fprintf(b, "\tv := min(g.Version, mustInterface(\"%s\").Version)\n", i.Name)
	b.WriteString("\tp, err := r.Bind(g, v)\n")
	b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	if hasHandler {
		fmt.Fprintf(b, "\tobj := &%s{p: p, h: h}\n", i.GoName)
		b.WriteString("\tif err := p.SetSink(obj); err != nil {\n\t\treturn nil, err\n\t}\n")
	} else {
		fmt.Fprintf(b, "\tobj := &%s{p: p}\n", i.GoName)
	}
	if i.Name == "wl_callback" {
		b.WriteString("\tp.markServerOwned()\n")
	}
	b.WriteString("\treturn obj, nil\n}\n\n")
}

func renderMeta(b *strings.Builder, p *protocol) {
	b.WriteString(generatedHeader)
	b.WriteString("package wayland\n\n")
	for _, i := range p.Interfaces {
		fmt.Fprintf(b, "var interface%s = &Interface{\n", i.GoName)
		fmt.Fprintf(b, "\tName: %q,\n\tVersion: %d,\n", i.Name, i.Version)
		b.WriteString("\tRequests: []Message{\n")
		for _, r := range i.Requests {
			fmt.Fprintf(b, "\t\t{Name: %q, Since: %d, Args: %s},\n", r.Name, r.Since, metaArgs(r.Args))
		}
		b.WriteString("\t},\n\tEvents: []Message{\n")
		for _, e := range i.Events {
			fmt.Fprintf(b, "\t\t{Name: %q, Since: %d, Args: %s},\n", e.Name, e.Since, metaArgs(e.Args))
		}
		b.WriteString("\t},\n}\n\n")
	}
	b.WriteString("var generatedInterfaces = map[string]*Interface{\n")
	for _, i := range p.Interfaces {
		fmt.Fprintf(b, "\t%q: interface%s,\n", i.Name, i.GoName)
	}
	b.WriteString("}\n")
}

func metaArgs(args []*arg) string {
	if len(args) == 0 {
		return "nil"
	}
	parts := make([]string, 0, len(args))
	for _, a := range args {
		parts = append(parts, fmt.Sprintf("{Name: %q, Type: %s, Interface: %q, Enum: %q, AllowNull: %t}", a.Name, argTypeConst(a.Type), a.Interface, a.Enum, a.AllowNull))
	}
	return "[]ArgSpec{" + strings.Join(parts, ", ") + "}"
}

func argTypeConst(t string) string {
	switch t {
	case "int":
		return "ArgInt"
	case "uint":
		return "ArgUint"
	case "fixed":
		return "ArgFixed"
	case "string":
		return "ArgString"
	case "array":
		return "ArgArray"
	case "fd":
		return "ArgFD"
	case "new_id":
		return "ArgNewID"
	case "object":
		return "ArgObject"
	}
	return "ArgUint"
}

func requestArgType(a *arg) (string, error) {
	switch a.Type {
	case "int":
		return "int32", nil
	case "uint":
		return "uint32", nil
	case "fixed":
		return "float64", nil
	case "string":
		if a.AllowNull {
			return "*string", nil
		}
		return "string", nil
	case "array":
		return "[]byte", nil
	case "fd":
		return "int", nil
	}
	return "", fmt.Errorf("%s: request arg type %q not implemented", a.Name, a.Type)
}

func requestExpr(a *arg, name string) (string, error) {
	switch a.Type {
	case "int":
		return "Int(" + name + ")", nil
	case "uint":
		return "Uint(" + name + ")", nil
	case "fixed":
		return "Fixed(" + name + ")", nil
	case "string":
		if a.AllowNull {
			return "String(" + name + ")", nil
		}
		return "String(&" + name + ")", nil
	case "array":
		return "Array(" + name + ")", nil
	case "fd":
		return "FD(" + name + ")", nil
	}
	return "", fmt.Errorf("%s: request arg type %q not implemented", name, a.Type)
}

func eventParams(e *msg) string {
	parts := make([]string, 0, len(e.Args))
	for _, a := range e.Args {
		parts = append(parts, safeName(a.Name)+" "+eventArgType(a))
	}
	return strings.Join(parts, ", ")
}

func eventArgType(a *arg) string {
	switch a.Type {
	case "int":
		return "int32"
	case "uint":
		return "uint32"
	case "fixed":
		return "float64"
	case "string":
		if a.AllowNull {
			return "*string"
		}
		return "string"
	case "array":
		return "[]byte"
	case "fd":
		return "int"
	case "new_id", "object":
		return "*Proxy"
	}
	return "any"
}

func eventExpr(a *arg, index int) string {
	switch a.Type {
	case "int":
		return fmt.Sprintf("args[%d].Int()", index)
	case "uint":
		return fmt.Sprintf("args[%d].Uint()", index)
	case "fixed":
		return fmt.Sprintf("args[%d].Fixed()", index)
	case "string":
		if a.AllowNull {
			return fmt.Sprintf("args[%d].StringPtr()", index)
		}
		return fmt.Sprintf("args[%d].String()", index)
	case "array":
		return fmt.Sprintf("args[%d].Array()", index)
	case "fd":
		return fmt.Sprintf("args[%d].FD()", index)
	case "new_id", "object":
		return fmt.Sprintf("args[%d].Proxy()", index)
	}
	return "nil"
}

func opcodeOf(i *iface, target *msg) int {
	for n, r := range i.Requests {
		if r == target {
			return n
		}
	}
	return -1
}

var goKeywords = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true,
	"default": true, "defer": true, "else": true, "fallthrough": true, "for": true,
	"func": true, "go": true, "goto": true, "if": true, "import": true,
	"interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
}

func safeName(s string) string {
	s = strings.ReplaceAll(s, "-", "_")
	if s == "" {
		return "arg"
	}
	if goKeywords[s] {
		return s + "_"
	}
	return s
}
