#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."
MOD="$(go list -m)"

pkg_list="$(mktemp)"
trap 'rm -f "$pkg_list"' EXIT
if ! go list -mod=mod -f '{{.ImportPath}}' ./... >"$pkg_list" 2>/dev/null; then
  echo "check-dep: no Go packages yet; dependency check deferred to L4"
  exit 0
fi
if [ ! -s "$pkg_list" ]; then
  echo "check-dep: no Go packages yet; dependency check deferred to L4"
  exit 0
fi

fail=0
edges="$(go list -mod=mod -f '{{.ImportPath}} {{join .Imports " "}}' ./...)"
pkgs="$(go list -mod=mod -f '{{.Name}} {{.ImportPath}}' ./...)"

# 1. 包名: 禁止层名, 杂物包, internal / pkg 目录.
while IFS=' ' read -r name path; do
  case "$name" in
    domain|service|repository|controller|utils|helpers|common)
      echo "forbidden package name: $path ($name)"
      fail=1
      ;;
  esac
  case "$path" in
    */internal|*/internal/*|*/pkg|*/pkg/*|*/cmd/waylandgen/*)
      echo "forbidden package path: $path"
      fail=1
      ;;
  esac
done <<< "$pkgs"

# 2. import 边.
while IFS=' ' read -r from imports; do
  for to in $imports; do
    case "$from" in
      "$MOD")
        case "$to" in
          "$MOD"/*) echo "$from -> $to"; fail=1 ;;
        esac
        ;;
      "$MOD"/protocols/*)
        case "$to" in
          "$MOD"|"$MOD"/protocols/*) ;;
          "$MOD"/*) echo "$from -> $to"; fail=1 ;;
        esac
        ;;
      "$MOD"/examples/*)
        case "$to" in
          "$MOD"|"$MOD"/protocols/*) ;;
          "$MOD"/*) echo "$from -> $to"; fail=1 ;;
        esac
        ;;
      "$MOD"/cmd/waylandgen)
        case "$to" in
          "$MOD"/*) echo "$from -> $to"; fail=1 ;;
        esac
        ;;
    esac

    # 3. 任何包都不 import 生成器 main.
    if [ "$to" = "$MOD/cmd/waylandgen" ] && [ "$from" != "$MOD/cmd/waylandgen" ]; then
      echo "$from -> $to"
      fail=1
    fi
  done
done <<< "$edges"

# 4. 生成文件头: protocols/ 下每个 .go 都必须是生成文件.
if [ -d protocols ]; then
  while IFS= read -r file; do
    first="$(head -n 1 "$file")"
    case "$first" in
      "// Code generated by waylandgen; DO NOT EDIT."*) ;;
      *) echo "not a generated file: $file"; fail=1 ;;
    esac
  done < <(find protocols -name '*.go' -type f)
fi

# 5. 第三方模块必须为 0.
mod_count="$(go list -mod=mod -m all | wc -l)"
if [ "$mod_count" -gt 1 ]; then
  echo "third-party modules present: $mod_count"
  fail=1
fi

if [ "$fail" -ne 0 ]; then
  exit 1
fi
echo "check-dep: OK"
